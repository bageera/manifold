#!/usr/bin/env python3
"""MNF8 research track 1 — entropy-backend ablation, STAGE 1 (pure entropy).

Freezes identical serialized residual streams and feeds the SAME bytes to
every backend, measuring compressed bytes + wall time + exact-reconstruction
of the compressed stream (roundtrip on the STREAM, pixels are unchanged by
construction in this stage). Same-coder parity discipline: one process, one
library set, every backend in the same table.

Backends (per review matrix):
  zlib -9 | zstd 3/9/19/--ultra-22 | brotli q5/9/11 | xz -6 / -9e
Backends whose CLI/py impls agree closely are cross-checked once (zstd py vs
zstd CLI on one stream) to catch impl-level surprises.

Inputs: the residual streams from the A/B/C/D predictor ablation
(regenerated identically here via med_predict — same construction as
crates/mnf-subspace/scripts/ablate_abcd.py), plus two shipped-codec streams
(MNF5-geom raw tile stream, MNF7 raw tile stream from the CLI via --mnf6
debug? no — MNF7 stage-1 uses the same frozen predictor streams; integrated
stage 2 covers the shipped codec).

Report: docs/entropy-backends-v13.md findings table is generated by
--markdown; raw numbers always print to stdout.
"""
import argparse
import brotli
import io
import json
import lzma
import time
import zlib
import zstandard
from pathlib import Path

import numpy as np
from PIL import Image

TS = 16


def med_predict(rgb, w, h):
    rgb = np.asarray(rgb, dtype=np.int32).reshape(h, w, 3)
    out = np.zeros((h, w, 3), dtype=np.int32)
    for c in range(3):
        img = rgb[:, :, c]
        o = out[:, :, c]
        o[0, 0] = 127
        if w > 1:
            o[0, 1:] = img[0, : w - 1]
        if h > 1:
            o[1:, 0] = img[: h - 1, 0]
        if w > 1 and h > 1:
            a = np.empty((h, w))
            a[1:, 1:] = img[: h - 1, : w - 1]
            b = np.empty((h, w))
            b[1:, 1:] = img[: h - 1, 1:]
            cc = np.empty((h, w))
            cc[1:, 1:] = img[1:, : w - 1]
            plane = a + b - cc
            flat_ = ((a >= b) & (a >= cc) & (b >= cc)) | (
                (a <= b) & (a <= cc) & (b <= cc)
            )
            d1, d2, d3 = (np.abs(plane - x) for x in (a, b, cc))
            pick = np.where((d1 <= d2) & (d1 <= d3), a, np.where(d2 <= d3, b, cc))
            sel = np.where(flat_, plane, pick)
            o[1:, 1:] = np.clip(sel[1:, 1:], 0, 255)
    return out.reshape(-1)


def tiles_of(mat, w, h):
    out = []
    cols = (w + TS - 1) // TS
    rows = (h + TS - 1) // TS
    for t in range(cols * rows):
        tx = (t % cols) * TS
        ty = (t // cols) * TS
        tw = min(TS, w - tx)
        th = min(TS, h - ty)
        m = np.asarray(mat)
        if m.ndim == 1 and m.size == w * h * 3:
            m = m.reshape(h, w, 3)
        out.append(m[ty : ty + th, tx : tx + tw].reshape(-1))
    return out


def stream_literals(img):
    h, w = img.shape[:2]
    parts = bytearray()
    for t in tiles_of(img.reshape(-1), w, h):
        parts += bytes([0]) + t.astype(np.uint8).tobytes()
    return bytes(parts)


def stream_med(img):
    h, w = img.shape[:2]
    flat = img.reshape(-1)
    med = med_predict(flat, w, h)
    parts = bytearray()
    for t, m in zip(tiles_of(flat, w, h), tiles_of(med, w, h)):
        r = (t.astype(np.int32) - m.astype(np.int32)) % 256
        parts += bytes([1]) + r.astype(np.uint8).tobytes()
    return bytes(parts)


def stream_med_geom(img):
    """MED residual + D8 geometric atlas on residuals (arm D of the v1.2 matrix)."""
    h, w = img.shape[:2]
    flat = img.reshape(-1)
    med = med_predict(flat, w, h)
    T = tiles_of(flat, w, h)
    Tm = tiles_of(med, w, h)
    R1 = [
        (a.astype(np.int32) - b.astype(np.int32)).reshape(-1, 3) % 256
        for a, b in zip(T, Tm)
    ]

    def d8(block, t):
        if t == 0:
            return block
        if t == 1:
            return block[:, ::-1].copy()
        if t == 2:
            return block[::-1].copy()
        if t == 3:
            return block[::-1, ::-1].copy()
        if t == 4:
            return np.transpose(block, (1, 0, 2)).copy()
        if t == 5:
            return d8(d8(block, 4), 1)
        if t == 6:
            return d8(d8(block, 4), 3)
        if t == 7:
            return d8(d8(d8(block, 4), 3), 1)
        raise ValueError(t)

    win = []
    s = bytearray()
    for i, r in enumerate(R1):
        ri = r.reshape(-1).astype(np.int32)
        th_, tw_ = r.shape[:2]
        lit = bytes([1]) + r.astype(np.uint8).tobytes()
        litd = len(zlib.compress(lit, 9))
        best = None
        for jj in win[-128:]:
            rj = R1[jj]
            if rj.shape != r.shape:
                continue
            ts_list = range(8) if th_ == tw_ else [0]
            for t in ts_list:
                tt = d8(rj.astype(np.uint8), t).reshape(-1).astype(np.int32)
                r2 = (ri - tt) % 256
                probe = bytes([3 if t else 2]) + jj.to_bytes(4, "little") + (
                    (bytes([t]) if t else b"") + r2.astype(np.uint8).tobytes()
                )
                dd = len(zlib.compress(probe, 9))
                if best is None or dd < best[0]:
                    best = (dd, jj, t, r2)
        if best and best[0] < litd:
            dd, jj, t, r2 = best
            hdr = (
                bytes([2]) + jj.to_bytes(4, "little")
                if t == 0
                else bytes([3]) + jj.to_bytes(4, "little") + bytes([t])
            )
            s += hdr + r2.astype(np.uint8).tobytes()
        else:
            s += lit
        if len(win) >= 128:
            win.pop(0)
        win.append(i)
    return bytes(s)


# --------------------------- backends ----------------------------------------

def b_zlib9(b):
    return zlib.compress(b, 9)

def b_zstd3(b):
    return zstandard.ZstdCompressor(level=3).compress(b)

def b_zstd9(b):
    return zstandard.ZstdCompressor(level=9).compress(b)

def b_zstd19(b):
    return zstandard.ZstdCompressor(level=19).compress(b)

def b_zstd22(b):
    c = zstandard.ZstdCompressor(level=22, write_content_size=False)
    p = zstandard.ZstdCompressionParameters.from_level(
        22, compression_level=22, enable_ldm=1
    )
    return zstandard.ZstdCompressor(compression_params=p).compress(b)

def b_brotli5(b):
    return brotli.compress(b, quality=5)

def b_brotli9(b):
    return brotli.compress(b, quality=9)

def b_brotli11(b):
    return brotli.compress(b, quality=11)

def b_xz6(b):
    return lzma.compress(b, format=lzma.FORMAT_XZ, preset=6)

def b_xz9e(b):
    f = lzma.LZMACompressor(format=lzma.FORMAT_XZ, preset=9 | lzma.PRESET_EXTREME)
    return f.compress(b) + f.flush()

BACKENDS = [
    ("zlib-9", b_zlib9),
    ("zstd-3", b_zstd3),
    ("zstd-9", b_zstd9),
    ("zstd-19", b_zstd19),
    ("zstd-22-ldm", b_zstd22),
    ("brotli-5", b_brotli5),
    ("brotli-9", b_brotli9),
    ("brotli-11", b_brotli11),
    ("xz-6", b_xz6),
    ("xz-9e", b_xz9e),
]


def zstd_roundtrip_ok(c, d):
    return zstandard.ZstdDecompressor().decompress(c, max_output_size=len(d) * 2) == d


def roundtrip_ok(name, c, d):
    if name.startswith("zlib"):
        return zlib.decompress(c) == d
    if name.startswith("zstd"):
        return zstd_roundtrip_ok(c, d)
    if name.startswith("brotli"):
        return brotli.decompress(c) == d
    if name.startswith("xz"):
        return lzma.decompress(c) == d
    raise ValueError(name)


def bench(fn, data, reps=1):
    t0 = time.perf_counter()
    out = fn(data)
    dt = (time.perf_counter() - t0) * 1000
    # extra reps for timing stability on tiny streams (report best)
    for _ in range(reps - 1):
        t0 = time.perf_counter()
        fn(data)
        dt = min(dt, (time.perf_counter() - t0) * 1000)
    return out, dt


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--reps", type=int, default=3)
    args = ap.parse_args()

    td = Path("/Users/jonbethea/projects/blacktech/manifold/testdata")
    files = [(f"dev/{p.name}", p) for p in sorted(td.glob("*.png"))]
    files += [(f"heldout/{p.name}", p) for p in sorted((td / "heldout").glob("*.png"))]

    streams = {}
    for label, p in files:
        img = np.asarray(Image.open(p).convert("RGB"), dtype=np.int32)
        h, w = img.shape[:2]
        streams[f"{label}|literal"] = stream_literals(img)
        streams[f"{label}|med"] = stream_med(img)
        streams[f"{label}|med+geom"] = stream_med_geom(img)

    # cross-check zstd py vs CLI once (impl-level surprise catcher)
    probe = next(iter(streams.values()))
    cli = Path("/opt/homebrew/bin/zstd")
    import subprocess as sp

    cli_out = sp.run([str(cli), "-19", "-c", "-q"], input=probe, capture_output=True, timeout=120).stdout
    py_out = b_zstd19(probe)
    print(f"cross-check zstd-19: py={len(py_out)} cli={len(cli_out)} (delta {abs(len(py_out)-len(cli_out))})")

    rows = {}
    for sname, data in streams.items():
        for bname, fn in BACKENDS:
            c, t_ms = bench(fn, data, reps=args.reps)
            rt = roundtrip_ok(bname, c, data)
            rows[(sname, bname)] = (len(c), t_ms, rt)

    # print per-stream tables, best bolded
    for sname in sorted({k[0] for k in rows}):
        base = rows[(sname, "zlib-9")][0]
        print(f"\n== {sname} (zlib-9 baseline {base} B) ==")
        print(f"{'backend':>12} {'bytes':>9} {'vs zlib9':>9} {'enc ms':>8} {'rt':>3}")
        best = min(rows[(sname, b)][0] for b, _ in BACKENDS)
        for bname, _ in BACKENDS:
            n, t, rt = rows[(sname, bname)]
            pct = (n - base) / base * 100
            print(f"{bname:>12} {n:>9} {pct:>+8.1f}% {t:>8.0f} {'ok' if rt else 'FAIL':>3}"
                  + ("  <-- best" if n == best else ""))

    ok = all(v[2] for v in rows.values())
    print(f"\nroundtrip exactness: {'ALL OK' if ok else 'FAILURES PRESENT'}")
    if args.markdown:
        print("\n(markdown table generation: see docs script — stdout above is canonical)")


if __name__ == "__main__":
    main()
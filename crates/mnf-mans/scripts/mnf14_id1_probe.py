QFP = 12

def quant_v(v, bits=16, fp=QFP):
    m = 1 << (bits - 1)
    return int(np.clip(round(v * (1 << fp)), -m, m - 1))


def law_constant(params, shp):
    h, w = shp
    return np.full((h, w, 3), params["k"], np.int64)


def law_plane(params, shp):
    h, w = shp
    a, b, c = params["a"], params["b"], params["c"]
    ys, xs = np.mgrid[0:h, 0:w]
    out = np.empty((h, w, 3), np.int64)
    for ch in range(3):
        out[..., ch] = (np.int64(a[ch]) +
                        ((np.int64(b[ch]) * xs + np.int64(c[ch]) * ys + (1 << (QFP - 1))) >> QFP))
    return np.clip(out, 0, 255)


def law_cos2(params, shp):
    n = shp[0]; N = 4096
    """two-component cosine field: A_j cos(kx_j x + ky_j y + phi_j), j=1,2;
    transport: per component per channel A i16 (RGB fp8), k i16 Q10, phi i16
    Q12-phase — decoder replays via a 4096-entry LUT (deterministic)."""
    N = 4096
    idx = np.arange(N)
    L = np.rint(np.cos(2 * np.pi * idx / N) * (1 << 14)).astype(np.int64)
    h, w = shp
    ys, xs = np.mgrid[0:h, 0:w]
    out = np.zeros((h, w, 3), np.int64)
    for j in ("1", "2"):
        A = params[f"A{j}"] if isinstance(params[f"A{j}"], list) else [params[f"A{j}"]] * 3
        kx = params[f"kx{j}"] if isinstance(params[f"kx{j}"], list) else [params[f"kx{j}"]] * 3
        ky = params[f"ky{j}"] if isinstance(params[f"ky{j}"], list) else [params[f"ky{j}"]] * 3
        ph = params[f"ph{j}"] if isinstance(params[f"ph{j}"], list) else [params[f"ph{j}"]] * 3
        for ch in range(3):
            # phase index over the LUT's 4096-turn lattice: (kx*x + ky*y + ph)
            # counts LUT steps; x,y in raw px; k params = LUT steps per px
            arg = (int(kx[ch]) * xs + int(ky[ch]) * ys + int(ph[ch])) % N
            acc = int(A[ch]) * L[arg]
            out[..., ch] += (acc + (1 << 13)) >> 14
    return np.clip(out, 0, 255)


def law_recurrence(params, shp):
    """first-order scan recurrence: v(k) = (a_c * v(k-1) + b_c) mod m_c —
    decoder replays the SAME raster scan."""
    h, w = shp
    a, b, m = params["ra"], params["rb"], params["rm"]
    out = np.empty((h, w, 3), np.int64)
    for ch in range(3):
        v = int(a[ch])
        acc = np.empty(h * w, np.int64)
        for k in range(h * w):
            acc[k] = v
            v = (a[ch] * v + b[ch]) % m[ch]
        out[..., ch] = acc.reshape(h, w)
    return out


def propose_plane_div(img, med, n):
    """EXACT-generative div-form plane (ADR-007 convention): per channel
    find (vx, vy, D, T) with  pixel(x,y) = clip((vx·x + vy·y + T) // D)
    EXACTLY. Bounded discovery: D from |vx|+|vy| magnitudes implied by the
    end-to-end finite differences (dx = img(x=1..)-img(x=0..) consistent
    step), then interval-intersection on T per row. Only EXACT solutions
    emit (zero residual by construction); partial = dropped."""
    h, w = img.shape[:2]
    out = []
    # candidate (vx, vy, D): scan D over {1..8} × step sizes implied by
    # observed finite diffs along a mid row/col
    for D in (1, 2, 3, 4, 6, 8):
        for vx in range(-8 * D, 8 * D + 1):
            for vy in range(-8 * D, 8 * D + 1):
                ok = True
                Ts = []
                for ch in range(0, 1):  # cheap precheck on R only
                    im = img[..., ch].astype(np.int64)
                    # horizontal consistency: im(x+1) − im(x) == vx/D (int)
                    # ⟺ ((vx·(x+1)+T)//D − (vx·x+T)//D) — verify on a mid row
                    y0 = h // 2
                    row = im[y0]
                    # solve T bounds from TWO pixels then verify the row:
                    # T ∈ [D·px − vx·x, D·px + D − 1 − vx·x] for every px
                    lo = max(D * int(row[x]) - vx * x for x in (0, w - 1))
                    hi = min(D * int(row[x]) + D - 1 - vx * x for x in (0, w - 1))
                    if lo > hi:
                        ok = False
                        break
                    T0 = lo  # any T in [lo, hi] works for the ROW; verify
                    if any((vx * x + T0) // D != int(row[x]) for x in range(w)):
                        ok = False
                        break
                if not ok:
                    continue
                # per-channel full verify + T interval across ALL rows
                params = {"vx": [], "vy": [], "D": D, "T": []}
                good = True
                for ch in range(3):
                    im = img[..., ch].astype(np.int64)
                    lo = -(10 ** 18); hi = 10 ** 18
                    for y in (0, h - 1):
                        row = im[y]
                        l = max(D * int(row[x]) - vx * x - vy * y for x in (0, w - 1))
                        u = min(D * int(row[x]) + D - 1 - vx * x - vy * y for x in (0, w - 1))
                        lo = max(lo, l); hi = min(hi, u)
                    if lo > hi:
                        good = False
                        break
                    T0 = lo
                    exact = True
                    for y in range(0, h, 7):  # strided rows first
                        if any((vx * x + vy * y + T0) // D != int(im[y, x]) for x in range(0, w, 7)):
                            exact = False
                            break
                    if not exact:
                        good = False
                        break
                    params["vx"].append(vx); params["vy"].append(vy); params["T"].append(int(np.clip(T0, -2 ** 31, 2 ** 31 - 1)))
                if good:
                    out.append(("planediv", params))
                    if len(out) >= 2:
                        return out
    return out


def law_planediv(params, shp):
    h, w = shp
    ys, xs = np.mgrid[0:h, 0:w]
    out = np.empty((h, w, 3), np.int64)
    for ch in range(3):
        out[..., ch] = np.clip((params["vx"][ch] * xs + params["vy"][ch] * ys +
                                params["T"][ch]) // params["D"], 0, 255)
    return out



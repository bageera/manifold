def gen_plane(n, seed):
    """ID1-A fixture = the WIRE LAW'S OWN REPLAY of random params —
    membership by construction; the discovery's task is inverting it."""
    r = np.random.default_rng(seed)
    params = {"a": [int(v) for v in r.integers(60, 200, 3)],
              "b": [int(v) for v in r.integers(-1536, 1537, 3)],
              "c": [int(v) for v in r.integers(-1536, 1537, 3)]}
    return law_plane(params, (n, n)), ("plane", params)


def gen_cos2(n, seed):
    r = np.random.default_rng(seed)
    kx1, ky1 = r.integers(2, 9), r.integers(2, 9)
    A = r.integers(20, 90, 3)
    ys, xs = np.mgrid[0:n, 0:n].astype(np.float64)
    ang1 = 2 * np.pi * (kx1 * xs / (n - 1) + ky1 * ys / (n - 1) + r.uniform(0, 2, 1))
    ang2 = 2 * np.pi * (r.integers(10, 30) * xs / (n - 1) + r.integers(10, 30) * ys / (n - 1))
    out = np.empty((n, n, 3), np.int64)
    for ch in range(3):
        val = 128 + A[ch] * np.cos(ang1) * 0.8 + 22 * np.cos(ang2)
        out[..., ch] = np.clip(np.round(val), 0, 255)
    truth = ("cos2-like", None)  # NOT exactly the cos2 law (two different freqs + amp mix)
    return out, truth


def gen_recurrence(n, seed):
    r = np.random.default_rng(seed)
    a = r.integers(3, 240, 3)
    b = r.integers(1, 250, 3)
    m = 251
    out = np.empty((n, n, 3), np.int64)
    for ch in range(3):
        v = int(a[ch])
        acc = np.empty(n * n, np.int64)
        for k in range(n * n):
            acc[k] = v
            v = (a[ch] * v + b[ch]) % m
        out[..., ch] = acc.reshape(n, n)
    return out, ("recurrence", {"ra": list(a), "rb": list(b), "rm": [m] * 3})


def gen_bands(n, seed):
    """ID1-B: top half = plane law, bottom half = cos2-ish law (composition).
    Both generated at n×n then cropped to n×(n//2) halves — cropping a
    plane keeps it a plane; cropping a cosine keeps its frequency."""
    top_full, _ = gen_plane(n, seed)
    bot_full, _ = gen_cos2(n, seed + 1)
    top = top_full[: n // 2]
    bottom = bot_full[n // 2:]
    return np.concatenate([top, bottom], axis=0), ("composed", None)


# ------------------------------------------------------------- proposers
def propose_plane(img, med, n):
    """fit per-channel plane on the RAW image (ID1's whole-frame law)."""
    h, w = img.shape[:2]
    err = img.astype(np.float64)
    ys, xs = np.mgrid[0:h, 0:w].astype(np.float64)
    u, v = xs / (w - 1), ys / (h - 1)
    # masked lstsq over UNCLIPPED samples (the clip region misleads lsq)
    mask = (img[..., 0] > 0) & (img[..., 0] < 255)
    keep = mask.ravel()
    M = np.stack([np.ones(u.ravel()[keep].size),
                  u.ravel()[keep], v.ravel()[keep]], axis=1)
    coefs = np.stack([np.linalg.lstsq(M, err[..., c].ravel()[keep], rcond=None)[0] for c in range(3)])
    # law replay: a + ((b·x + c·y) >> QFP) with x RAW px — b_wire = rate per
    # raw px at QFP = (rate per unit-u) / (w-1) quantized
    params = {"a": [int(np.clip(round(coefs[c, 0]), -32767, 32767)) for c in range(3)],
              "b": [int(np.clip(round(coefs[c, 1] / (w - 1) * (1 << QFP)), -32768, 32767)) for c in range(3)],
              "c": [int(np.clip(round(coefs[c, 2] / (h - 1) * (1 << QFP)), -32768, 32767)) for c in range(3)]}
    return [("plane", params)]


def propose_cos2(img, med, n):
    """FFT peak on the LUMA error plane → dominant (kx, ky); per-channel
    DC + cos + sin fit at that peak (decoder replay = the cos2 law's
    component 1; component 2 zeroed)."""
    h, w = img.shape[:2]
    err = img.astype(np.float64) - 128.0  # raw content, DC-anchored
    luma = err.mean(axis=2)
    F = np.fft.fftshift(np.fft.fft2(luma))
    mag = np.abs(F)
    mag[h // 2, w // 2] = 0  # drop DC
    iy, ix = np.unravel_index(np.argmax(mag), mag.shape)
    ky, kx = iy - h // 2, ix - w // 2
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    ang = 2 * np.pi * (kx * xx / (w - 1) + ky * yy / (h - 1))
    N = 4096
    params = {}
    # component 1 = dominant peak; component 2 = zeroed (honest: the arm
    # only carries what it fit — residual absorbs the rest)
    A1 = [] ; PH1 = []
    for ch in range(3):
        D = np.stack([np.ones(ang.size), np.cos(ang).ravel(), np.sin(ang).ravel()], axis=1)
        coef, *_ = np.linalg.lstsq(D, err[..., ch].ravel(), rcond=None)
        B, S = coef[1], coef[2]
        A1.append(int(np.clip(round(np.hypot(B, S)), -32767, 32767)))
        # phi: A'·cos(ang+phi) = A'[cosang·cosphi − sinang·sinphi]; match
        # B=cosang coef, S=sinang coef ⟹ A'cosphi=B, A'sinphi=−S
        PH1.append(int(round((np.arctan2(-S, B) / (2 * np.pi)) % 1.0 * N)) % N)
    # k per whole-span cycles → law lattice: LUT steps per raw px = cycles·N/(n-1)
    kx_q = int(round(kx * N / (n - 1))) % N
    ky_q = int(round(ky * N / (n - 1))) % N
    params = {"A1": A1, "A2": [0, 0, 0],
              "kx1": kx_q, "ky1": ky_q, "ph1": PH1,
              "kx2": 0, "ky2": 0, "ph2": 0}
    return [("cos2", params)]


def propose_recurrence(img, med, n):
    """first-order raster recurrence per channel: v(k) = (a·v(k-1) + b) mod m
    with RAW a (i16), b (i16), m (u8) = 5 B/channel."""
    flat = img.reshape(-1, 3).astype(np.float64)
    ra, rb, rm = [], [], []  # recurrence proposer = wrapped LSQ (best effort)
    for ch in range(3):
        v = flat[:, ch]
        v0, v1 = v[:-1], v[1:]
        A = np.stack([v0, np.ones_like(v0)], axis=1)
        coef, *_ = np.linalg.lstsq(A, v1, rcond=None)
        ra.append(int(np.clip(round(coef[0]), 0, 32767)))
        rb.append(int(np.clip(round(coef[1]), -32767, 32767)))
        rm.append(251)
    return [("recurrence", {"ra": ra, "rb": rb, "rm": rm})]


def propose_recurrence_mod(img, med, n):
    """modular-arithmetic inversion of the raster recurrence: from ANY
    observed pair sequence find (a, b) over Z_m such that v(k) = (a·v(k-1)+b)
    mod m for ALL k — exact search: for candidate m in {251, 253, 255, 256},
    test the pair-consistency of consecutive observed values:
    v1 = (a·v0 + b) mod m ⟺ (v1 - v2) = a·(v0 - v2) mod m (b eliminated);
    solve a by trying all a in 0..m-1 (m ≤ 256 → cheap) checking consistency
    on a strided sample of pairs, then verify the FULL sequence, and only
    emit the candidate on a full-match (zero residual expected)."""
    m_for = img.reshape(-1, 3)
    out = []
    for m in (251, 253, 255, 256):
        ok_all = True
        ras = []
        rbs = []
        for ch in range(3):
            v = m_for[:, ch].astype(np.int64)
            a_c = None
            for a in range(m):
                # b determined from the first pair; FORWARD-VERIFY the whole
                # scan (the relation is between CONSECUTIVE states only — a
                # strided check is invalid; HF-lesson: forward replay is the
                # honest verification anyway)
                b = (v[1] - a * v[0]) % m
                if np.array_equal((a * v[:-1] + b) % m, v[1:]):
                    a_c = (a, b)
                    break
            if a_c is None:
                ok_all = False
                break
            ras.append(a_c[0]); rbs.append(a_c[1])
        if ok_all:
            out.append(("recurrence", {"ra": ras, "rb": rbs, "rm": [m] * 3}))
    return out


def propose_all(img, med, n):
    cands = [("const", {"k": [int(v) for v in np.median(img.reshape(-1, 3), axis=0)]})]
    cands += propose_plane(img, med, n)
    cands += propose_cos2(img, med, n)
    cands += propose_recurrence(img, med, n)
    cands += propose_recurrence_mod(img, med, n)
    cands += propose_plane_div(img, med, n)
    return cands

# ------------------------------------------------------------- discovery
def decode_cost(img, med, name, params, vec):
    """honest complete-record cost: replay the DECODER-EXACT law."""
    pred_law = VOCAB_PRED[name](params, img.shape[:2])
    res = (img - pred_law) % 256
    assert np.array_equal((pred_law + res) % 256, img % 256), "recon inexact"
    wire = cd_g(res).astype(np.uint8)
    return FRAME + len(ZC.compress(wire.tobytes())) + VOCAB_TRANSPORT[name]()


def discover(img):
    med = med_plane(img)
    cands = propose_all(img, med, img.shape[0])
    scored = [(decode_cost(img, med, nm, pr, img.shape[:2]), nm) for nm, pr in cands]
    scored.sort(key=lambda t: t[0])
    base = arm(img, med, 0)
    best_cost, best_name = scored[0]
    picked = best_cost if best_cost < base else None
    # the PICK = min(base, discovered law arm) — never-worse by construction
    total = min(base, best_cost) if best_name else base
    return {"base_med": base, "best_law": best_name, "best_cost": best_cost,
            "pick": total, "picked": picked is not None}


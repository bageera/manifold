# ---------------------------------------------------------------- wire utils
def cd_g(res):
    return np.stack([(res[..., 1]) % 256,
                     (res[..., 0] - res[..., 1]) % 256,
                     (res[..., 2] - res[..., 1]) % 256], axis=-1)


def arm(px, pred, tp):
    res = (px - pred) % 256
    assert np.array_equal((pred + res) % 256, px % 256), "recon inexact"
    return FRAME + len(ZC.compress(cd_g(res).astype(np.uint8).tobytes())) + tp



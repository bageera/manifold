#!/usr/bin/env python3
"""Generate MNF10 conformance fixtures (ADR-007 prototype promotion, Track A).

Golden vectors: one per model id (1..6), each a deterministic small body whose
pixels are generated by the model's own normative equation (the fixture IS the
class the pick must fire on), serialized through the research crate's payload
builders + a 32-B MNF10 header (magic "MNF10", same field layout as MNF8,
payload_len = body, flags/backend = 0).

Rejections: reserved id 0, reserved id 7, truncated body per model, piecewise
boundary out of range, bilinear at degenerate dims.

Everything byte-reproducible; run before the conformance test when the
grammar changes.
"""
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
OUT = ROOT / "tests/conformance"
CRATE = ROOT / "crates/mnf-mans"

MAGIC = b"MNF9"  # 4-byte magic per the ADR-003 reservation; "MNF10" = track name
W, H = 96, 64


def header(w, h, payload_len):
    b = MAGIC
    b += struct.pack("<IIII", w, h, 16, (w + 15) // 16 * ((h + 15) // 16))
    b += struct.pack("<III", payload_len, 0, 0)  # flags=0, backend=0
    return b


def gen_pixels_const(w, h, rgb):
    return bytes(rgb) * (w * h)


def gen_pixels_div1d(w, h):
    # (N*x + T)//D with D = w-1 = 95 for the 96-wide fixture; endpoints
    # 20->230, 230->20, 60->200 (Jon's home turf, convention-scaled)
    D = w - 1
    px = bytearray(w * h * 3)
    for x in range(w):
        v = [(20 * D + x * 210) // D,
             (230 * D - x * 210) // D,
             (60 * D + x * 140) // D]
        for c in range(3):
            if not 0 <= v[c] <= 255:
                sys.exit(f"div1d value out of range at x={x}: {v}")
            px[(x * 3) + c] = v[c]
            for y in range(1, h):
                px[((y * w + x) * 3) + c] = v[c]
    return bytes(px)


def gen_pixels_rec1(w, h):
    px = bytearray(w * h * 3)
    for x in range(w):
        v = [(30 + 7 * x) % 256, (200 + 7 * x) % 256, (90 + 7 * x) % 256]
        for y in range(h):
            px[(y * w + x) * 3:(y * w + x) * 3 + 3] = bytes(v)
    return bytes(px)


def gen_pixels_bilin_joint(w, h):
    corners = ([15, 225, 90], [245])  # placeholder naming resolved below
    # per-channel corner values (c00,c10,c01,c11):
    C = [(15, 225, 90, 245), (200, 30, 90, 240), (70, 180, 20, 240)]
    px = bytearray(w * h * 3)
    dm = (w - 1) * (h - 1)
    for y in range(h):
        for x in range(w):
            for c in range(3):
                (c00, c10, c01, c11) = C[c]
                v = (c00 * (w - 1 - x) * (h - 1 - y) + c10 * x * (h - 1 - y)
                     + c01 * (w - 1 - x) * y + c11 * x * y) // dm
                px[(y * w + x) * 3 + c] = v
    return bytes(px)


def gen_pixels_bilin_nested(w, h):
    # per-channel nested round-lerp (top row from (c00,c10), bottom from
    # (c01,c11), then y-round-lerp between them); corners as in the payload.
    C = [(15, 225, 90, 245), (200, 30, 90, 240), (70, 180, 20, 240)]
    px = bytearray(w * h * 3)
    dx, dy = w - 1, h - 1
    hx, hy = dx // 2, dy // 2
    for y in range(h):
        for x in range(w):
            for c in range(3):
                (c00, c10, c01, c11) = C[c]
                t = c00 + (x * (c10 - c00) + hx) // dx
                b = c01 + (x * (c11 - c01) + hx) // dx
                v = t + (y * (b - t) + hy) // dy
                px[(y * w + x) * 3 + c] = v
    return bytes(px)


def gen_pixels_piecewise(w, h, bounds=(0, 48, 96), a0=(20, 10, 60), a1=(130, 120, 150), b1=(230, 235, 200)):
    px = bytearray(w * h * 3)
    for x in range(w):
        if x < bounds[1]:
            n = bounds[1] - bounds[0] - 1
            v = [a0[c] + x * (a1[c] - a0[c]) // n for c in range(3)]
        else:
            n = bounds[2] - bounds[1] - 1
            sx = x - bounds[1]
            v = [a1[c] + sx * (b1[c] - a1[c]) // n for c in range(3)]
        for y in range(h):
            px[(y * w + x) * 3:(y * w + x) * 3 + 3] = bytes(v)
    return bytes(px)


def build_payloads():
    """Call the research crate's builders through a scratch test binary."""
    test_main = r'''
// scratch: emit each model's payload hex to stdout
use mnf_mans::mnf10::*;
fn main() {
    let p1 = payload_const([7, 7, 7]);
    println!("{}", hex(&p1));
    // div-1D for the 96-wide fixture: D = 95 (index 3 = w-1); endpoints
    // 20->230, 230->20, 60->200 → N = total rise per full span: 210/-210/140,
    // T = a0*D.
    let p2 = payload_div1d([(210, 20 * 95), (-210, 230 * 95), (140, 60 * 95)], 3);
    println!("{}", hex(&p2));
    let p3 = payload_rec1([(30u8, 7i16), (200, 7), (90, 7)], 0);
    println!("{}", hex(&p3));
    let p4 = payload_bilinear([[15, 200, 70], [225, 30, 180], [90, 90, 20], [245, 240, 240]], false);
    println!("{}", hex(&p4));
    let p5 = payload_bilinear([[15, 200, 70], [225, 30, 180], [90, 90, 20], [245, 240, 240]], true);
    println!("{}", hex(&p5));
    // piecewise: [0,48) 20->130ish per channel, [48,96) 130->230
    let segs = vec![
        PiecewiseSeg { x_start: 0, per_channel: [(110, 20 * 47, 3), (110, 10 * 47, 3), (90, 60 * 47, 3)] },
        PiecewiseSeg { x_start: 48, per_channel: [(100, 130 * 47, 3), (115, 120 * 47, 3), (50, 150 * 47, 3)] },
    ];
    let p6 = payload_piecewise(&segs).unwrap();
    println!("{}", hex(&p6));
}
fn hex(b: &[u8]) -> String { b.iter().map(|x| format!("{x:02x}")).collect() }
'''
    scratch = CRATE / "examples"
    scratch.mkdir(exist_ok=True)
    (scratch / "mnf10_dump.rs").write_text(test_main)
    import os
    env = {**os.environ,
           "PATH": "/opt/homebrew/opt/rustup/bin:"
                   + str(Path.home() / ".rustup/toolchains/stable-aarch64-apple-darwin/bin")
                   + ":" + os.environ["PATH"],
           "RUSTUP_HOME": str(Path.home() / ".rustup")}
    r = subprocess.run(["cargo", "run", "--quiet", "-p", "mnf-mans", "--example", "mnf10_dump"],
                       capture_output=True, text=True, cwd=ROOT, env=env, timeout=300)
    if r.returncode != 0:
        sys.exit(r.stderr[-1500:])
    lines = r.stdout.strip().splitlines()
    if len(lines) != 6:
        sys.exit(f"expected 6 payload lines from mnf10_dump, got {len(lines)}: {lines}")
    return [bytes.fromhex(l.strip()) for l in lines]


def main():
    payloads = build_payloads()
    (c1, c2, c3, c4, c5, c6) = payloads
    # W=96: the div-1D convention denominator is w-1 = 95 → the payload's
    # (N,T) must be solved for 96-wide, not the 160-wide home-turf numbers.
    fixture_map = {
        "mnf10_const_96x64.mnf10": (c1, gen_pixels_const(W, H, (7, 7, 7))),
        "mnf10_div1d_96x64.mnf10": (c2, gen_pixels_div1d(W, H)),
        "mnf10_rec1_96x64.mnf10": (c3, gen_pixels_rec1(W, H)),
        "mnf10_bilin_joint_96x64.mnf10": (c4, gen_pixels_bilin_joint(W, H)),
        "mnf10_bilin_nested_96x64.mnf10": (c5, gen_pixels_bilin_nested(W, H)),
        "mnf10_piecewise_96x64.mnf10": (c6, gen_pixels_piecewise(W, H)),
    }
    for (name, (payload, pixels)) in fixture_map.items():
        buf = header(W, H, len(payload)) + payload
        with open(OUT / name, "wb") as f:
            f.write(buf)
        with open(OUT / (name.replace(".mnf10", ".expected.pixels")), "wb") as f:
            f.write(pixels)
        print(f"{name}: payload={len(payload)} file={len(buf)} pixels={len(pixels)}")

    # rejections, all built on the div-1D golden body
    def hdr_with(plen):
        return header(W, H, plen)

    # reserved id 0
    b = bytearray(hdr_with(4)); b += bytes([0, 0, 0, 0])
    with open(OUT / "rej_mnf10_reserved_id0.mnf10", "wb") as f:
        f.write(bytes(b))
    # reserved id 7
    b = bytearray(hdr_with(4)); b += bytes([7, 0, 0, 0])
    with open(OUT / "rej_mnf10_reserved_id7.mnf10", "wb") as f:
        f.write(bytes(b))
    # truncated body (cut the div1d params)
    b = bytearray(hdr_with(10)); b += c2[:10]
    with open(OUT / "rej_mnf10_truncated.mnf10", "wb") as f:
        f.write(bytes(b))
    # piecewise boundary out of range: rebuild with boundary 999
    pw_bad = bytearray(c6)
    # boundaries live right after nseg (offset 2): u16 LE
    struct.pack_into("<H", pw_bad, 2, 999)
    b = bytearray(hdr_with(len(pw_bad))); b += pw_bad
    with open(OUT / "rej_mnf10_pw_boundary.mnf10", "wb") as f:
        f.write(bytes(b))
    # D index out of table (div1d): last param byte
    bad = bytearray(c2); bad[-1] = 9
    b = bytearray(hdr_with(len(bad))); b += bad
    with open(OUT / "rej_mnf10_bad_dindex.mnf10", "wb") as f:
        f.write(bytes(b))
    # bad magic (the audit-history lesson: name it what it is)
    good = bytearray((OUT / "mnf10_const_96x64.mnf10").read_bytes())
    good[0:4] = b"MNF1X"[:4]          # slice-assign on bytearray RESIZES if
    # the RHS is longer — a 5-byte RHS would silently grow the file
    with open(OUT / "rej_mnf10_bad_magic.mnf10", "wb") as f:
        f.write(bytes(good))
    print("rejection fixtures written")


if __name__ == "__main__":
    main()